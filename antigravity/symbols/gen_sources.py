#!/usr/bin/env python3
"""Generate the C++ stub header and Python mirror from `src/procdef.h`'s BOOKS.

Run from antigravity/:
    python3 -m symbols.gen_sources <symbols.json> <symbols_gen.h>   # C++ header (gitignored)
    python3 -m symbols.gen_sources --books [<books.py>]             # Python mirror (checked in)

The C++ header adds the build id, original frame sizes, and precise entry pointer
maps from symbols.json. Register masks come from validated morestack spills and
ArgsPointerMaps[0]; the stack map excludes those register spill homes.

The checked-in Python mirror backs public `pyagy.BOOKS` and ships in the wheel. Its embedded
interpreter imports must remain stdlib-only. Run `pixi run shim-books` after editing the C table.
"""
import json
import os
import sys
from collections.abc import Sequence
from typing import NotRequired, TypedDict, cast

from .agyelf import Book, BookTarget, EntryGCMap, active_rows, load_procdef
from .x86 import decode_frame

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
BOOKS_OUT = os.path.join(ROOT, "pyagy", "agy_process", "books.py")


class FrameMetadata(TypedDict):
    prologues: dict[str, str]
    gc_maps: dict[str, EntryGCMap]
    planner_response_itab: int
    build_id: NotRequired[str]


# --- src/symbols_gen.h --------------------------------------------------------------------------
def frame_size(row: BookTarget, phex: str) -> int:
    """Decode one complete, canonically encoded Go frame prologue."""
    hid = row["id"]
    try:
        prologue = bytes.fromhex(phex)
        go_frame, consumed = decode_frame(prologue)
        if consumed != len(prologue):
            raise ValueError("trailing bytes after frame setup")
    except ValueError as exc:
        raise SystemExit(f"book {hid} ({row['symbol']}): invalid frame prologue {phex!r}: {exc}") from exc
    return go_frame


def gen_header(symbols_path: str, out_path: str) -> None:
    with open(symbols_path) as f:
        metadata = cast(FrameMetadata, json.load(f))
    prologues = metadata["prologues"]
    build_id = metadata.get("build_id", "")
    planner_itab = metadata["planner_response_itab"]
    if not 0 < planner_itab < (1 << 64) or planner_itab % 8:
        raise SystemExit("invalid planner response itab")
    stubs: list[tuple[str, int, int, int, int]] = []
    for row in active_rows(load_procdef()):
        frame = frame_size(row, prologues[row["symbol"]])
        roots = metadata["gc_maps"][row["symbol"]]
        regmask, stack_size, stackmask = (roots["reg_ptrmask"], roots["stack_args_size"],
                                        roots["stack_ptrmask"])
        if (not 0 <= regmask < (1 << 9) or not 0 <= stack_size <= 512 or stack_size % 8
                or stackmask < 0 or stackmask >> (stack_size // 8)):
            raise SystemExit(f"book {row['id']}: invalid entry GC bitmap")
        stubs.append((row["id"], frame, regmask, stack_size, stackmask))

    with open(out_path, "w") as f:
        w = f.write
        w("/* generated by gen_sources.py — do not edit */\n")
        w("#ifndef AGY_SYMBOLS_GEN_H\n#define AGY_SYMBOLS_GEN_H\n\n")
        w(f'inline constexpr char AGY_BUILD_ID[] = "{build_id}";\n\n')
        w(f"inline constexpr unsigned long long AGY_PLANNER_RESPONSE_ITAB = {planner_itab:#x};\n\n")
        w("/* id, original frame allocation, saved-GP pointer mask, stack-argument\n"
          " * bitmap extent in bytes, and stack-argument pointer mask. */\n")
        w("#define AGY_STUBS(X) \\\n")
        w(" \\\n".join(f'    X("{hid}", {frame:#x}, {regmask:#x}, {stack_size}, {stackmask:#x})'
                      for hid, frame, regmask, stack_size, stackmask in stubs) + "\n")
        w("\n#endif /* AGY_SYMBOLS_GEN_H */\n")

    print(f"wrote {out_path} ({len(stubs)} stubs, build-id {build_id})")


# --- pyagy/agy_process/books.py -----------------------------------------------------------------
BOOKS_HEADER = '''"""Machine-readable mirror of BOOKS, the book table in src/procdef.h.

GENERATED — do not edit by hand. Regenerate with::

    pixi run shim-books

`pyagy.BOOKS` is a public introspection surface, so this file is checked in and ships in the
wheel. Stdlib-pure: agy_process imports it inside the linked CLI's embedded interpreter.

Each row mirrors one C row:
  id      the row's name, the `bk("id")` key at the C call sites
  symbol  the Go symbol the book patches
  mode    "async" (log) | "sync" (block for a modify verdict)
  kind    the same name, as the tag passed to dispatch(kind, stream_id, data)
  mech    "off" (not installed) | "fullcgo" | "asmcgo" — the cgocall trampoline flavour
  retcap  return-capture policy (0 none, <0 special, >0 min bytes); every retcap != 0 row is off
"""

from typing import Literal, TypedDict


class Book(TypedDict):
    id: str
    symbol: str
    mode: Literal["async", "sync"]
    kind: str
    mech: Literal["off", "fullcgo", "asmcgo"]
    retcap: int


BOOKS: list[Book] = [
'''

BOOKS_FOOTER = ''']

#: kinds the Python layer DERIVES rather than receiving straight from a book.
DERIVED_KINDS = ("genai_turn", "h2msg", "conversation_id", "callstack", "app_response",
                 "system_message_capture_error", "response_capture_error")


def by_mech(mech: str) -> list[Book]:
    """Rows whose install mechanism is `mech` ("off" / "fullcgo" / "asmcgo")."""
    return [h for h in BOOKS if h["mech"] == mech]


def by_kind(kind: str) -> list[Book]:
    """Rows emitting `kind`."""
    return [h for h in BOOKS if h["kind"] == kind]


def enabled_books() -> list[Book]:
    """Rows actually installed at runtime (everything not mech="off")."""
    return [h for h in BOOKS if h["mech"] != "off"]


def sync_capable() -> list[Book]:
    """Rows that wait for dispatch completion (mode="sync")."""
    return [h for h in BOOKS if h["mode"] == "sync"]
'''


def render_books(rows: Sequence[Book]) -> str:
    out = [BOOKS_HEADER]
    for r in rows:
        out.append(
            '    {{"id": {id!r}, "symbol": {symbol!r},\n'
            '     "mode": {mode!r}, "kind": {kind!r}, "mech": {mech!r}, "retcap": {retcap!r}}},\n'
            .format(**r, kind=r["id"]))
    out.append(BOOKS_FOOTER)
    return "".join(out)


def gen_books(out_path: str) -> None:
    rows = load_procdef()
    with open(out_path, "w") as f:
        f.write(render_books(rows))
    print(f"wrote {out_path} ({len(rows)} rows, {len(active_rows(rows))} installed)")


def main() -> None:
    argv = sys.argv[1:]
    if argv and argv[0] == "--books":
        if len(argv) > 2:
            raise SystemExit("usage: python3 -m symbols.gen_sources --books [<books.py>]")
        gen_books(argv[1] if len(argv) == 2 else BOOKS_OUT)
        return
    if len(argv) != 2:
        raise SystemExit("usage: python3 -m symbols.gen_sources <symbols.json> <symbols_gen.h>\n"
                         "       python3 -m symbols.gen_sources --books [<books.py>]")
    gen_header(argv[0], argv[1])


if __name__ == "__main__":
    main()
