#!/usr/bin/env python3
"""Generate the sources derived from BOOKS, the book table in `src/procdef.h`.

Run from antigravity/:
    python3 -m symbols.gen_sources <symbols.json> <symbols_gen.h>   # C++ header (gitignored)
    python3 -m symbols.gen_sources --hooks [<hooks.py>]             # Python mirror (checked in)

`src/symbols_gen.h` holds only what the C++ can't take from BOOKS: this build's id, and
`AGY_STUBS`, the literals each installed row's stub asm needs (expanded by `src/goframe.cpp`).

`pyagy/agy_process/hooks.py` backs the public `pyagy.BOOKS`. It ships in the wheel and is imported
inside the CLI's embedded interpreter, so it is checked in, not rebuilt: run `pixi run shim-hooks`
after editing the C table.
"""
import json
import os
import sys

from .agyelf import active_rows, load_procdef

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
BOOKS_OUT = os.path.join(ROOT, "pyagy", "agy_process", "hooks.py")


# --- src/symbols_gen.h --------------------------------------------------------------------------
def stub_entry(row: dict, book: int, phex: str) -> str:
    """One `FULLCGO/ASMCGO(id, book, bytes...)` entry of AGY_STUBS."""
    hid = row["id"]
    ow = len(phex) // 2
    if ow not in (8, 11):
        raise SystemExit(f"hook {hid} ({row['symbol']}): unexpected prologue hex {phex!r} (ow={ow})")
    pbytes = ", ".join(f"0x{phex[j:j + 2]}" for j in range(0, len(phex), 2))
    stub = row["mech"].upper()
    return f"{stub}({hid}, {book}, {pbytes})"


def gen_header(symbols_path: str, out_path: str) -> None:
    d = json.load(open(symbols_path))
    prologues = d["prologues"]
    all_rows = load_procdef()
    book = {r["id"]: i for i, r in enumerate(all_rows)}
    rows = active_rows(all_rows)

    with open(out_path, "w") as f:
        w = f.write
        w("/* generated by gen_sources.py — do not edit */\n")
        w("#ifndef AGY_SYMBOLS_GEN_H\n#define AGY_SYMBOLS_GEN_H\n\n")
        w('inline constexpr char AGY_BUILD_ID[] = "%s";\n\n' % d.get("build_id", ""))
        w("/* FULLCGO/ASMCGO(id, book, displaced bytes...) in BOOKS order */\n")
        w("#define AGY_STUBS(FULLCGO, ASMCGO) \\\n")
        for r in rows:
            sym = r["symbol"]
            w("    %s \\\n" % stub_entry(r, book[r["id"]], prologues[sym]))
        w("\n#endif /* AGY_SYMBOLS_GEN_H */\n")

    print("wrote %s (%d stubs, build-id %s)" % (out_path, len(rows), d.get("build_id", "")))


# --- pyagy/agy_process/hooks.py -----------------------------------------------------------------
BOOKS_HEADER = '''"""Machine-readable mirror of BOOKS, the book table in src/procdef.h.

GENERATED — do not edit by hand. Regenerate with::

    pixi run shim-hooks

`pyagy.BOOKS` is a public introspection surface, so this file is checked in and ships in the
wheel. Stdlib-pure: agy_process imports it inside the instrumented CLI's embedded interpreter.

Each row mirrors one C row:
  id      the row's name, the `bk("id")` key at the C call sites
  symbol  the Go symbol the hook patches
  mode    "async" (log) | "sync" (block for a modify verdict)
  kind    the same name, as the tag passed to dispatch(kind, stream_id, data)
  mech    "off" (not installed) | "fullcgo" | "asmcgo" — the cgocall trampoline flavour
  retcap  return-capture policy (0 none, <0 special, >0 min bytes); every retcap != 0 row is off
"""

BOOKS = [
'''

BOOKS_FOOTER = ''']

#: kinds the Python layer DERIVES rather than receiving straight from a hook.
DERIVED_KINDS = ("genai_turn", "h2msg", "conversation_id", "callstack", "app_response")


def by_mech(mech):
    """Rows whose install mechanism is `mech` ("off" / "fullcgo" / "asmcgo")."""
    return [h for h in BOOKS if h["mech"] == mech]


def by_kind(kind):
    """Rows emitting `kind`."""
    return [h for h in BOOKS if h["kind"] == kind]


def enabled_hooks():
    """Rows actually installed at runtime (everything not mech="off")."""
    return [h for h in BOOKS if h["mech"] != "off"]


def sync_capable():
    """Rows whose dispatch can return replacement bytes (mode="sync")."""
    return [h for h in BOOKS if h["mode"] == "sync"]
'''


def render_hooks(rows) -> str:
    out = [BOOKS_HEADER]
    for r in rows:
        out.append(
            '    {{"id": {id!r}, "symbol": {symbol!r},\n'
            '     "mode": {mode!r}, "kind": {kind!r}, "mech": {mech!r}, "retcap": {retcap!r}}},\n'
            .format(**r, kind=r["id"]))
    out.append(BOOKS_FOOTER)
    return "".join(out)


def gen_hooks(out_path: str) -> None:
    rows = load_procdef()
    open(out_path, "w").write(render_hooks(rows))
    n_on = sum(1 for r in rows if r["mech"] != "off")
    print(f"wrote {out_path} ({len(rows)} hooks, {n_on} installed)")


def main() -> None:
    argv = sys.argv[1:]
    if argv and argv[0] == "--hooks":
        if len(argv) > 2:
            raise SystemExit("usage: python3 -m symbols.gen_sources --hooks [<hooks.py>]")
        gen_hooks(argv[1] if len(argv) == 2 else BOOKS_OUT)
        return
    if len(argv) != 2:
        raise SystemExit("usage: python3 -m symbols.gen_sources <symbols.json> <symbols_gen.h>\n"
                         "       python3 -m symbols.gen_sources --hooks [<hooks.py>]")
    gen_header(argv[0], argv[1])


if __name__ == "__main__":
    main()
