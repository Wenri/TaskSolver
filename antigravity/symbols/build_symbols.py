#!/usr/bin/env python3
"""Resolve the Go functions listed in `src/procdef.h` inside the stripped, Propeller/BOLT-reordered
agy image and write symbols.json for the native host.

The hook list is NOT repeated here: the targets, the ELF/pclntab parsing and the prologue
arithmetic all come from `agyelf.py`, so this tool and `make_libagy.py` cannot disagree about where
a hook lands. Adding a hook is a `procdef.h` edit plus `pixi run shim-symbols`.

Verification: every *installed* row (`AGY_FULLGO(symbol)`/`AGY_ASMGO(symbol)`) must resolve to a
Go function entry with a recoverable frame prologue, or this exits non-zero —
that is the tripwire for an agy layout change. Retired (`AGY_OFF(symbol)`) rows are resolved too (so
re-enabling one is a procdef edit), but a stale address there only warns: several are frameless
leaf getters that legitimately have no prologue.

Usage (from antigravity/):  python3 -m symbols.build_symbols <agy-binary> <out.json>
"""
import gzip
import json
import os
import sys

from .agyelf import GoImage, active_rows, hook_targets, load_procdef


def main():
    if len(sys.argv) != 3:
        raise SystemExit("usage: python3 -m symbols.build_symbols <agy-binary> <out.json>")
    binpath, outpath = sys.argv[1], sys.argv[2]

    rows = load_procdef()
    targets = hook_targets(rows)
    installed = {r["symbol"] for r in active_rows(rows)}

    d = open(binpath, "rb").read()
    img = GoImage(d)
    name2addr = {}
    funcmap = []                             # (addr, name) for EVERY func -> stack symbolization
    for addr, nm in img.functions():
        if nm not in name2addr:
            name2addr[nm] = addr
        funcmap.append((addr, nm))

    hooks, skips, prologues, missing, unverified, soft = {}, {}, {}, [], [], []
    for nm in targets:
        if nm not in name2addr:
            missing.append(nm)
            continue
        a = name2addr[nm]
        hooks[nm] = a
        skips[nm] = img.prologue_skip(a)
        prologues[nm] = img.frame_prologue_hex(a, skips[nm])
        if not img.is_prologue(a) or (skips[nm] > 0 and not prologues[nm]):
            (unverified if nm in installed else soft).append(nm)

    out = {
        "agy_path": binpath,
        "build_id": img.elf.build_id(),
        "ptr_size": img.ptr_size,
        "moduledata_vaddr": img.md_vaddr,
        "text_base": img.text_base,
        "minpc": img.minpc,
        "total_funcs": img.nfunc,
        "hooks": hooks,
        "skips": skips,
        "prologues": prologues,
        "missing": missing,
    }
    with open(outpath, "w") as f:
        json.dump(out, f, indent=2)

    # Full sorted funcmap (addr -> name for EVERY function) for offline stack symbolization
    # (pyagy.agy_process.symbolize). Gzipped and gitignored: it is ~1 MB, specific to one agy
    # build, and regenerated by `pixi run shim-symbols`. Keyed by absolute link vaddr so it is
    # ASLR-independent: a captured runtime PC maps via link_vaddr = pc - module_base, then bisect.
    funcmap.sort()
    fmpath = os.path.join(os.path.dirname(os.path.abspath(outpath)), "funcmap.tsv.gz")
    with gzip.open(fmpath, "wt", encoding="utf-8") as f:
        for addr, nm in funcmap:
            f.write(f"{addr:x}\t{nm}\n")

    print(f"wrote {outpath}")
    print(f"  funcmap:    {fmpath} ({len(funcmap)} funcs)")
    print(f"  build-id:   {out['build_id']}")
    print(f"  moduledata: {img.md_vaddr:#x}   text_base: {img.text_base:#x}"
          + (f"   minpc: {img.minpc:#x}" if img.minpc else ""))
    print(f"  funcs:      {img.nfunc}")
    print(f"  hooks:      {len(hooks)}/{len(targets)}" + (f"  MISSING={missing}" if missing else ""))
    for nm in targets:
        if nm in hooks:
            flag = ("  !! NOT A PROLOGUE" if nm in unverified else
                    "  (retired, unverified)" if nm in soft else
                    "" if nm in installed else "  (retired)")
            print(f"    {hooks[nm]:#012x} (+{skips[nm]:2d})  {nm}{flag}")
    if soft:
        print(f"  WARNING: {len(soft)} retired row(s) no longer resolve to a Go prologue: {soft}")
    if unverified or missing:
        raise SystemExit(f"FAILED verification: missing={missing} unverified={unverified}")
    print(f"  all {len(installed)} installed hook addresses verified as Go prologues ✓")


if __name__ == "__main__":
    main()
